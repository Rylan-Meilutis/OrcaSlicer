std::optional<LearnedTimingFeatures> extract_learned_timing_features(
    std::istream &input, const std::string &context, const std::string &hash,
    const std::function<void()> &checkpoint)
{
    if (!valid_key(context) || !valid_key(hash)) return std::nullopt;
    LearnedTimingFeatures result;
    result.gcode_hash = hash;
    // Orca may emit both legacy and project wipe-tower positions under the same
    // key. Retain every value (and equal-key order), rather than ignoring one.
    std::multimap<std::string, std::string> config;
    bool in_config = false, saw_config = false, complete_config = false;
    std::size_t bytes = 0, config_bytes = 0, lines = 0;
    std::string line, previous_tool, generator;
    // Bounded line reader: getline alone could allocate an arbitrarily large
    // malicious line before its length could be checked.
    while (input.good()) {
        line.clear();
        char c;
        while (input.get(c)) {
            if (++bytes > 256u * 1024u * 1024u) return std::nullopt;
            if (c == '\n') break;
            if (line.size() >= 256u * 1024u) return std::nullopt;
            if (c != '\r') line += c;
        }
        if (++lines % 4096 == 0 && checkpoint) checkpoint();
        constexpr const char *generator_prefix = "; generated by OrcaSlicer ";
        if (line.compare(0, std::char_traits<char>::length(generator_prefix), generator_prefix) == 0) {
            if (!generator.empty()) return std::nullopt;
            generator = line.substr(std::char_traits<char>::length(generator_prefix));
            const auto timestamp = generator.find(" on ");
            if (timestamp != std::string::npos) generator.resize(timestamp);
            if (generator.empty() || generator.size() > 128 ||
                generator.find_first_not_of("0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ.-+_") != std::string::npos)
                return std::nullopt;
        }
        if (line == "; CONFIG_BLOCK_START") {
            if (saw_config) return std::nullopt;
            saw_config = in_config = true;
            continue;
        }
        if (line == "; CONFIG_BLOCK_END") {
            if (!in_config) return std::nullopt;
            in_config = false;
            complete_config = true;
            continue;
        }
        if (in_config) {
            config_bytes += line.size();
            if (config_bytes > 4u * 1024u * 1024u) return std::nullopt;
            const auto equals = line.find(" = ");
            if (line.compare(0, 2, "; ") != 0 || equals == std::string::npos) return std::nullopt;
            config.emplace(line.substr(2, equals - 2), line.substr(equals + 3));
            continue;
        }
        constexpr const char *prefix = "; estimated printing time (normal mode) = ";
        if (line.compare(0, std::char_traits<char>::length(prefix), prefix) == 0) {
            if (result.baseline_seconds != 0.) return std::nullopt;
            std::istringstream duration(line.substr(std::char_traits<char>::length(prefix)));
            double amount;
            char unit;
            while (duration >> std::ws && !duration.eof()) {
                if (!(duration >> amount >> unit)) return std::nullopt;
                if (!std::isfinite(amount) || amount < 0.) return std::nullopt;
                const double factor = unit == 'd' ? 86400. : unit == 'h' ? 3600. : unit == 'm' ? 60. : unit == 's' ? 1. : 0.;
                if (factor == 0.) return std::nullopt;
                result.baseline_seconds += amount * factor;
            }
            if (!duration.eof()) return std::nullopt;
        }
        std::istringstream command_line(line);
        std::string command;
        command_line >> command;
        if (command == "M109" || command == "M190" || command == "M191") ++result.heater_waits;
        if (command == "G12" || command == "G27" || command == "P0") ++result.cleaner_calls;
        if (command == "G427" || command == "G28" || command == "G29") ++result.calibration_calls;
        if (command.size() > 1 && command.front() == 'T' &&
            command.find_first_not_of("0123456789", 1) == std::string::npos) {
            if (!previous_tool.empty() && previous_tool != command) ++result.tool_changes;
            previous_tool = command;
        }
    }
    if (input.bad() || !complete_config || in_config || config.empty() || generator.empty()) return std::nullopt;
    for (const char *key : {"printer_model", "gcode_flavor", "nozzle_diameter", "filament_type",
                            "machine_start_gcode", "change_filament_gcode"})
        if (config.find(key) == config.end()) return std::nullopt;
    boost::uuids::detail::sha1 digest;
    constexpr char schema[] = "Orca learned timing source features v1";
    digest.process_bytes(schema, sizeof(schema));
    digest.process_bytes(generator.data(), generator.size());
    digest.process_byte(0);
    digest.process_bytes(context.data(), context.size());
    for (const auto &entry : config) {
        digest.process_byte(0);
        digest.process_bytes(entry.first.data(), entry.first.size());
        digest.process_byte(0);
        digest.process_bytes(entry.second.data(), entry.second.size());
    }
    boost::uuids::detail::sha1::digest_type words;
    digest.get_digest(words);
    std::ostringstream encoded;
    encoded << std::hex << std::setfill('0');
    for (auto word : words) encoded << std::setw(2 * sizeof(word)) << static_cast<unsigned int>(word);
    result.compatibility_key = encoded.str();
    return valid_features(result) ? std::optional<LearnedTimingFeatures>(result) : std::nullopt;
}

bool LearnedTimingModel::add_observation(const LearnedTimingObservation &observation)
{
    if (!observation.completed || !observation.pause_excluded || !valid_key(observation.job_id) ||
        !valid_features(observation.features) || !std::isfinite(observation.active_seconds) ||
        observation.active_seconds <= 0.) return false;
    if (std::any_of(m_observations.begin(), m_observations.end(), [&](const auto &existing) {
        return existing.job_id == observation.job_id;
    })) return false;
    if (m_observations.size() == maximum_observations) m_observations.erase(m_observations.begin());
    m_observations.push_back(observation);
    return true;
}

std::optional<LearnedTimingEstimate> LearnedTimingModel::estimate(const LearnedTimingFeatures &features) const
{
    if (!valid_features(features)) return std::nullopt;
    std::vector<double> residuals;
    for (const auto &observation : m_observations)
        if (compatible(features, observation.features))
            residuals.push_back(observation.active_seconds - observation.features.baseline_seconds);
    if (residuals.size() < minimum_samples) return std::nullopt;
    std::sort(residuals.begin(), residuals.end());
    const std::size_t middle = residuals.size() / 2;
    const double median = residuals.size() % 2 ? residuals[middle] :
                          0.5 * residuals[middle - 1] + 0.5 * residuals[middle];
    LearnedTimingEstimate result;
    result.seconds = features.baseline_seconds + median;
    result.lower_seconds = features.baseline_seconds + residuals.front();
    result.upper_seconds = features.baseline_seconds + residuals.back();
    result.sample_count = residuals.size();
    // Implausible transferred corrections fail closed rather than clipping into
    // an apparently useful estimate. No observed component is added twice.
    if (!std::isfinite(result.upper_seconds) || result.lower_seconds <= 0.) return std::nullopt;
    return result;
}
