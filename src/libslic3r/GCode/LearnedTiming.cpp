bool valid_key(const std::string &key) { return !key.empty() && key.size() <= 512; }

bool valid_features(const LearnedTimingFeatures &f)
{
    return valid_key(f.compatibility_key) && valid_key(f.gcode_hash) &&
           std::isfinite(f.baseline_seconds) && f.baseline_seconds > 0. &&
           std::isfinite(f.motion_seconds) && f.motion_seconds >= 0. &&
           f.motion_seconds <= f.baseline_seconds;
}

bool close(double a, double b)
{
    // Conservative interpolation neighborhood; never extrapolate a short job's
    // unexplained overhead onto a substantially longer or different-stage job.
    return std::abs(a - b) <= 0.2 * std::max(a, b);
}

bool compatible(const LearnedTimingFeatures &a, const LearnedTimingFeatures &b)
{
    if (a.compatibility_key != b.compatibility_key) return false;
    // Even matching file hashes require consistent extracted features.
    return close(a.baseline_seconds, b.baseline_seconds) && close(a.motion_seconds, b.motion_seconds) &&
           close(a.tool_changes, b.tool_changes) && close(a.heater_waits, b.heater_waits) &&
           close(a.cleaner_calls, b.cleaner_calls) && close(a.calibration_calls, b.calibration_calls);
}
